# 1. 变量：用来存数据（密钥、提示词、对话内容都靠它）
# 格式：变量名 = 内容

# 模拟存储 AK / SK（火山方舟密钥）
AccessKey = "这里写你的AK"
SecretKey = "这里写你的SK"

# 模拟存储 提示词（给AI的指令）
system_prompt = "你是一个专业的AI大模型助手，回答简洁、准确、有用"
user_question = "什么是大模型API调用？"

# 2. print：把内容打印出来看结果
print("======== 第三天学习 ========")
print("我的 AK：", AccessKey)
print("我的 SK：", SecretKey)
print("\n系统提示词：", system_prompt)
print("用户问题：", user_question)

